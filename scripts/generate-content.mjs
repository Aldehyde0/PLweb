import { readdirSync, readFileSync, mkdirSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, relative, dirname } from 'node:path';
import { parseArticle, validateArticles, compileArticle } from './mdx-pipeline.mjs';

const root=resolve('content/concepts');
function files(dir) {return readdirSync(dir,{withFileTypes:true}).flatMap(e=>e.isDirectory()?files(resolve(dir,e.name)):e.name.endsWith('.mdx')?[resolve(dir,e.name)]:[]);}
export async function generateContent({check=false,sample=false}={}) {
 const articles=files(root).map(file=>parseArticle(readFileSync(file,'utf8'),relative(process.cwd(),file).replaceAll('\\','/'))).sort((a,b)=>a.metadata.order-b.metadata.order);
 const knowledge=JSON.parse(readFileSync('content/external-knowledge.json','utf8'));
 if(!sample)validateArticles(articles,knowledge);
 for(const a of articles) if(!a.file.startsWith(`content/concepts/${a.metadata.category}/`)) throw new Error(`${a.file}: 文件方向与 category 不一致`);
 if(check) await Promise.all(articles.map(a=>compileArticle(readFileSync(a.file,'utf8'),a.file)));
 const index=Object.fromEntries(articles.map(a=>[a.metadata.slug,{concept:a.concept,longForm:a.longForm,sections:a.sections,order:a.metadata.order,directory:a.metadata.directory,file:a.file,searchText:a.searchText,anchorAliases:a.metadata.anchorAliases??{},demos:a.demos.map(d=>({name:d.name,kind:d.attributes.find(x=>x.name==='kind')?.value}))}]));
 const outputs={
  'lib/generated/content-index.json':JSON.stringify(index,null,2)+'\n',
  'lib/generated/mdx-registry.ts':`// Generated by scripts/generate-content.mjs. Do not edit.\nexport const articleLoaders = {\n${articles.map(a=>`  '${a.metadata.slug}': () => import('../../${a.file}'),`).join('\n')}\n};\n`,
 };
 for(const [file,value] of Object.entries(outputs)) {
   if(check && (!existsSync(file)||readFileSync(file,'utf8')!==value)) throw new Error(`${file} 已过期；运行 npm run content:generate`);
   if(!check) {mkdirSync(dirname(file),{recursive:true}); if(!existsSync(file)||readFileSync(file,'utf8')!==value)writeFileSync(file,value);}
 }
 console.log(`${check?'Checked':'Generated'} ${articles.length} MDX articles`);
 return articles;
}
if(process.argv[1]&&resolve(process.argv[1])===resolve(new URL(import.meta.url).pathname.replace(/^\/([A-Z]:)/i,'$1'))) await generateContent({check:process.argv.includes('--check'),sample:process.argv.includes('--sample')});
